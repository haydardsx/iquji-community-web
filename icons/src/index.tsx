export type IqujiIconName = keyof typeof IQUJI_ICONS;

type IqujiIconAccessibility =
  | { decorative?: true; label?: never }
  | { decorative: false; label: string };

export type IqujiIconProps = Omit<
  IconSvgProps,
  "aria-hidden" | "aria-label" | "children" | "role"
> &
  IqujiIconAccessibility & {
    name: IqujiIconName;
  };

export function IqujiIcon({
  decorative = true,
  label,
  name,
  size = 18,
  strokeWidth = 1.8,
  ...svgProps
}: IqujiIconProps) {
  const Icon = IQUJI_ICONS[name];
  return (
    <Icon
      aria-hidden={decorative ? "true" : undefined}
      aria-label={decorative ? undefined : label}
      focusable="false"
      role={decorative ? undefined : "img"}
      size={size}
      strokeWidth={strokeWidth}
      {...svgProps}
    />
  );
}
